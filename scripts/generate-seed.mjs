import { readFileSync, writeFileSync } from "node:fs";
const lessons = JSON.parse(
  readFileSync(new URL("../src/data/course.json", import.meta.url)),
);
const knowledge = JSON.parse(
  readFileSync(new URL("../src/data/knowledge.json", import.meta.url)),
);
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const lessonColumns = [
  "day",
  "title",
  "topic",
  "icon",
  "lesson",
  "goal",
  "prompt",
  "rule",
];
const rows = lessons
  .map(
    (row) =>
      `(${lessonColumns.map((k) => (k === "day" ? row[k] : quote(row[k]))).join(",")})`,
  )
  .join(",\n");
const entries = knowledge
  .map(
    (row) =>
      `(${[quote(row.id), quote(row.title), `array[${row.keywords.map(quote).join(",")}]::text[]`, quote(row.explanation), quote(row.example)].join(",")})`,
  )
  .join(",\n");
writeFileSync(
  new URL("../supabase/seed.sql", import.meta.url),
  `-- Generated by npm run db:seed:generate. Re-running updates curriculum, not student records.\nbegin;\ninsert into public.lessons (${lessonColumns.join(",")}) values\n${rows}\non conflict (day) do update set ${lessonColumns
    .filter((k) => k !== "day")
    .map((k) => `${k}=excluded.${k}`)
    .join(
      ",",
    )};\ninsert into public.knowledge_entries (id,title,keywords,explanation,example) values\n${entries}\non conflict (id) do update set title=excluded.title,keywords=excluded.keywords,explanation=excluded.explanation,example=excluded.example;\ncommit;\n`,
);
console.log(
  `Generated ${lessons.length} lessons and ${knowledge.length} knowledge entries.`,
);
// One reviewable SQL file for environments without a migration CLI.
writeFileSync(
  new URL("../supabase/setup.sql", import.meta.url),
  ["schema.sql", "001_learning.sql", "seed.sql"]
    .map((name) =>
      readFileSync(new URL(`../supabase/${name}`, import.meta.url), "utf8"),
    )
    .join("\n"),
);
