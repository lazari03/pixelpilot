import { readFileSync, writeFileSync } from "node:fs";
const lessons = JSON.parse(
  readFileSync(new URL("../src/data/course.json", import.meta.url)),
);
const knowledge = JSON.parse(
  readFileSync(new URL("../src/data/knowledge.json", import.meta.url)),
);
const quote = (value) => `'${String(value).replaceAll("'", "''")}'`;
const lessonColumns = [
  "day",
  "title",
  "topic",
  "icon",
  "lesson",
  "goal",
  "prompt",
  "rule",
];
const rows = lessons
  .map(
    (row) =>
      `(${lessonColumns.map((k) => (k === "day" ? row[k] : quote(row[k]))).join(",")})`,
  )
  .join(",\n");
const entries = knowledge
  .map(
    (row) =>
      `(${[quote(row.id), quote(row.title), `array[${row.keywords.map(quote).join(",")}]::text[]`, quote(row.explanation), quote(row.example)].join(",")})`,
  )
  .join(",\n");
writeFileSync(
  new URL("../supabase/seed.sql", import.meta.url),
  `-- Generated by npm run db:seed:generate. Re-running updates curriculum, not student records.\nbegin;\ninsert into public.lessons (${lessonColumns.join(",")}) values\n${rows}\non conflict (day) do update set ${lessonColumns
    .filter((k) => k !== "day")
    .map((k) => `${k}=excluded.${k}`)
    .join(
      ",",
    )};\ninsert into public.knowledge_entries (id,title,keywords,explanation,example) values\n${entries}\non conflict (id) do update set title=excluded.title,keywords=excluded.keywords,explanation=excluded.explanation,example=excluded.example;\ncommit;\n`,
);
console.log(
  `Generated ${lessons.length} lessons and ${knowledge.length} knowledge entries.`,
);
// One reviewable SQL file for environments without a migration CLI.
writeFileSync(
  new URL("../supabase/setup.sql", import.meta.url),
  ["schema.sql", "001_learning.sql", "seed.sql"]
    .map((name) =>
      readFileSync(new URL(`../supabase/${name}`, import.meta.url), "utf8"),
    )
    .join("\n"),
);
const chapters = JSON.parse(
  readFileSync(new URL("../src/data/chapters.json", import.meta.url)),
);
const challenges = JSON.parse(
  readFileSync(new URL("../src/data/challenges.json", import.meta.url)),
);
const questions = JSON.parse(
  readFileSync(new URL("./content/questions.private.json", import.meta.url)),
);
const json = (value) => `${quote(JSON.stringify(value))}::jsonb`;
const expanded = `\nbegin;\ninsert into public.course_chapters(day,content) values ${chapters.map((c) => `(${c.day},${json(c)})`).join(",\n")} on conflict(day) do update set content=excluded.content;\ninsert into public.course_challenges(id,day,level,slot,content) values ${challenges.map((c) => `(${quote(c.id)},${c.day},${quote(c.level)},${c.slot},${json(c)})`).join(",\n")} on conflict(id) do update set content=excluded.content;\ninsert into public.course_questions(id,day,text,options,answer,explanation) values ${questions.map((q) => `(${quote(q.id)},${q.day},${json(q.text)},${json(q.options)},${q.answer},${json(q.explanation)})`).join(",\n")} on conflict(id) do update set text=excluded.text,options=excluded.options,answer=excluded.answer,explanation=excluded.explanation;\ncommit;\n`;
writeFileSync(
  new URL("../supabase/seed-course.sql", import.meta.url),
  expanded,
);
writeFileSync(
  new URL("../supabase/setup.sql", import.meta.url),
  [
    "schema.sql",
    "001_learning.sql",
    "002_course.sql",
    "003_roles.sql",
    "seed.sql",
    "seed-course.sql",
  ]
    .map((name) =>
      readFileSync(new URL(`../supabase/${name}`, import.meta.url), "utf8"),
    )
    .join("\n"),
);
console.log(
  `Generated ${chapters.length} chapters, ${challenges.length} challenges, ${questions.length} private questions.`,
);
